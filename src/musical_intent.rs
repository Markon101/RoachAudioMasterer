//! Musical Intent Engine & Adaptive Intelligence Controller (Roach Audio Evolution).
//!
//! Replaces brute-force corrective engineering with perceptual musical awareness:
//! 1. Identifies the primary Musical Operating Regime:
//!    - `Preserve`: High organic cohesion, deliberate warmth, high crest acoustic dynamics.
//!      Guards artistic intent (intimate stereo, intentional saturation, delicate dynamics).
//!    - `Restore`: Hard objective evidence of degradation (steep brickwall band-limiting cliff,
//!      out-of-phase sub mud, accidental phase jitter). Specialists activate with full authority.
//!    - `Enhance`: Commercial mix with solid foundation needing air shimmer, correlation-aware 3D depth,
//!      and dynamic post-mastering punch.
//!    - `Explore`: Explicitly creative multi-timescale acoustic field expansion.
//!
//! 2. Evaluates Perceptual Intent Metrics:
//!    - `intimacy_score`: Inherent spatial closeness vs stadium width.
//!    - `dynamic_contrast_budget`: Preserves musical tension and release without compression clamping.
//!    - `tonal_deliberation_index`: Distinguishes intentional harmonic overtones from high-frequency noise.
//!    - `organic_warmth_factor`: Protects warm vintage roll-offs from false "high-band loss" alarms.
//!
//! 3. Generates Adaptive Intent Directives for downstream pipeline stages:
//!    - Modulates SFHT sub-bass authority and gain.
//!    - Modulates CFM mid-flow authority and strength.
//!    - Modulates De-fizz desmear and phase continuity.
//!    - Modulates 3D spatial width factor and room depth.
//!    - Modulates 4D Port-Hamiltonian modal coupling (kappa), quartic beta, and air shelf.
//!    - Modulates glue compressor threshold, ratio, and time-constants.

use crate::assess::AcousticProfile;
use crate::scene_stats::{SceneStats, TuningCard};
use serde::{Deserialize, Serialize};

/// The four operational regimes of Roach Audio.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum MusicalRegime {
    /// Leave intentional structure substantially untouched; protect warmth, crest factor, and intimacy.
    Preserve,
    /// Correct physical defects with decisive evidence of degradation (e.g. out-of-phase sub mud, brickwall loss).
    Restore,
    /// Add bounded clarity, spatial depth, harmonic focus, and dynamic polish.
    Enhance,
    /// Explicitly creative acoustic transformations beyond strict fidelity.
    Explore,
}

impl std::fmt::Display for MusicalRegime {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            MusicalRegime::Preserve => write!(f, "PRESERVE (Artistic Identity & Warmth Guard)"),
            MusicalRegime::Restore => write!(f, "RESTORE (Physical Defect Correction)"),
            MusicalRegime::Enhance => write!(f, "ENHANCE (Acoustic Depth & Polished Polish)"),
            MusicalRegime::Explore => write!(f, "EXPLORE (Creative 4D Phase Expansion)"),
        }
    }
}

/// Inspectable perceptual intent scores in [0.0, 1.0].
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct PerceptualIntentScores {
    /// Spatial intimacy vs broad expansive field (1.0 = intimate centered vocal/ballad, 0.0 = wide stadium).
    pub intimacy_score: f32,
    /// Macro-dynamic contrast budget (1.0 = wide symphonic/acoustic dynamics, 0.0 = dense compressed wall-of-sound).
    pub dynamic_contrast_budget: f32,
    /// Tonal deliberation index (1.0 = intentional harmonic synthesis/chords, 0.0 = noisy/incoherent).
    pub tonal_deliberation_index: f32,
    /// Organic warmth factor (1.0 = smooth natural roll-off, 0.0 = steep brickwall codec cliff).
    pub organic_warmth_factor: f32,
    /// Intentional saturation confidence (1.0 = artistic drive/fuzz, 0.0 = accidental digital clipping).
    pub intentional_saturation_confidence: f32,
}

/// Adaptive directives that govern downstream pipeline behavior.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct IntentDirectives {
    pub regime: MusicalRegime,
    pub sub_bass_authority_scale: f32,
    pub mid_flow_authority_scale: f32,
    pub defizz_desmear_scale: f32,
    pub spatial_width_scale: f32,
    pub room_depth_scale: f32,
    pub port_hamiltonian_shelf_db: f32,
    pub port_hamiltonian_kappa: f32,
    pub port_hamiltonian_beta: f32,
    pub glue_compressor_ratio: f32,
    pub glue_compressor_threshold_db: f32,
    pub summary_rationale: String,
}

/// Full Musical Intent Card generated by offline whole-song scene assessment.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct MusicalIntentCard {
    pub regime: MusicalRegime,
    pub intent_scores: PerceptualIntentScores,
    pub directives: IntentDirectives,
}

impl MusicalIntentCard {
    /// Formulates a Musical Intent Card from measured acoustic profile and deep statistics.
    pub fn analyze(profile: &AcousticProfile, stats: &SceneStats) -> Self {
        // 1. Evaluate Intimacy Score
        // High correlation (> 0.85), modest side-to-mid ratio (< 0.35), and gentle high-band energy
        let corr_clamped = profile.interchannel_correlation.clamp(0.0, 1.0);
        let intimacy_score = (corr_clamped * (1.0 - profile.side_to_mid_ratio.clamp(0.0, 0.8))).clamp(0.0, 1.0);

        // 2. Evaluate Dynamic Contrast Budget
        // Dynamic spread (L10 - L90) + transient crest factor
        let spread = stats.dynamics.dynamic_spread_db;
        let dynamic_contrast_budget = ((spread - 4.0) / 8.0).clamp(0.0, 1.0);

        // 3. Evaluate Tonal Deliberation Index
        // Harmonic fraction + HNR
        let h_frac = stats.entropy_hnr.harmonic_fraction;
        let hnr_norm = ((stats.entropy_hnr.hnr_db + 10.0) / 25.0).clamp(0.0, 1.0);
        let tonal_deliberation_index = (0.5 * h_frac + 0.5 * hnr_norm).clamp(0.0, 1.0);

        // 4. Evaluate Organic Warmth Factor vs Brickwall Loss
        // Steep cliff (> -18 dB/oct in high band) with near-zero Wiener flatness indicates loss.
        // Smooth gentle roll-off (-6 to -14 dB/oct) with high flatness indicates deliberate warm mastering.
        let high_band = stats.band_slopes.iter().find(|b| b.name == "high");
        let (high_slope, high_flatness) = high_band
            .map(|b| (b.slope_db_per_octave, b.wiener_flatness))
            .unwrap_or((-12.0, 0.40));
        eprintln!("DEBUG high_slope: {}, high_flatness: {}", high_slope, high_flatness);

        let organic_warmth_factor = if high_slope < -22.0 && high_flatness < 0.20 {
            0.10 // Physical band-limit loss: needs Restoration
        } else if high_slope < -6.0 && (high_flatness > 0.20 || tonal_deliberation_index > 0.60) {
            0.90 // Natural organic warmth: Preserve
        } else {
            0.50 // Moderate commercial tilt
        };

        // 5. Evaluate Intentional Saturation vs Accidental Clipping
        // Zero sample clipping overs with high crest factor and high HNR = intentional warm saturation
        let clipping_samples = profile.clipping_sample_count;
        let intentional_saturation_confidence = if clipping_samples == 0 && tonal_deliberation_index > 0.70 {
            0.95
        } else if clipping_samples > 10 {
            0.15
        } else {
            0.60
        };

        let intent_scores = PerceptualIntentScores {
            intimacy_score,
            dynamic_contrast_budget,
            tonal_deliberation_index,
            organic_warmth_factor,
            intentional_saturation_confidence,
        };

        // 6. Regime Classification Policy
        let sub_instability = profile.artifacts.sub_instability;
        let phase_haze = profile.artifacts.phase_haze;
        let is_severely_degraded = sub_instability > 0.45 || phase_haze > 0.20 || organic_warmth_factor < 0.25;

        let regime = if is_severely_degraded {
            MusicalRegime::Restore
        } else if organic_warmth_factor > 0.75 && dynamic_contrast_budget > 0.65 {
            MusicalRegime::Preserve
        } else if intimacy_score < 0.30 && dynamic_contrast_budget < 0.35 {
            MusicalRegime::Explore
        } else {
            MusicalRegime::Enhance
        };

        // 7. Generate Stage Directives
        let directives = match regime {
            MusicalRegime::Preserve => IntentDirectives {
                regime,
                sub_bass_authority_scale: 0.50,
                mid_flow_authority_scale: 0.60,
                defizz_desmear_scale: 0.40, // protect sharp transients & deliberate bite
                spatial_width_scale: 0.85,  // protect tight intimate center
                room_depth_scale: 0.50,     // preserve dry acoustic closeness
                port_hamiltonian_shelf_db: (0.20 + 0.50 * (1.0 - organic_warmth_factor)).clamp(0.20, 0.80), // don't force bright sizzle on warm tracks
                port_hamiltonian_kappa: 5.5,
                port_hamiltonian_beta: 1.2,
                glue_compressor_ratio: 1.15, // light, transparent glue
                glue_compressor_threshold_db: -14.0,
                summary_rationale: "High organic cohesion & acoustic dynamic range detected. Guarding warm tonal balance and natural transient dynamics.".to_string(),
            },
            MusicalRegime::Restore => IntentDirectives {
                regime,
                sub_bass_authority_scale: 1.00,
                mid_flow_authority_scale: 1.00,
                defizz_desmear_scale: 1.00,
                spatial_width_scale: 1.00,
                room_depth_scale: 1.00,
                port_hamiltonian_shelf_db: 1.50, // compensate severe high-frequency roll-off
                port_hamiltonian_kappa: 6.20,
                port_hamiltonian_beta: 2.20,
                glue_compressor_ratio: 1.25,
                glue_compressor_threshold_db: -14.0,
                summary_rationale: "Physical degradation detected (out-of-phase sub mud or steep band-limit loss). Engaging full restoration specialists.".to_string(),
            },
            MusicalRegime::Enhance => IntentDirectives {
                regime,
                sub_bass_authority_scale: 0.85,
                mid_flow_authority_scale: 0.85,
                defizz_desmear_scale: 0.75,
                spatial_width_scale: 1.10,
                room_depth_scale: 0.90,
                port_hamiltonian_shelf_db: 1.20,
                port_hamiltonian_kappa: 6.18,
                port_hamiltonian_beta: 1.80,
                glue_compressor_ratio: 1.22,
                glue_compressor_threshold_db: -14.0,
                summary_rationale: "Balanced modern mix. Applying correlation-aware spatial staging, dynamic 4D Port-Hamiltonian air, and true-peak mastering.".to_string(),
            },
            MusicalRegime::Explore => IntentDirectives {
                regime,
                sub_bass_authority_scale: 0.90,
                mid_flow_authority_scale: 0.95,
                defizz_desmear_scale: 0.60,
                spatial_width_scale: 1.25,
                room_depth_scale: 1.20,
                port_hamiltonian_shelf_db: 1.50,
                port_hamiltonian_kappa: 7.00,
                port_hamiltonian_beta: 2.50,
                glue_compressor_ratio: 1.28,
                glue_compressor_threshold_db: -15.0,
                summary_rationale: "Expansive creative headroom available. Activating multi-scale spatial depth and heightened Port-Hamiltonian cross-coupling.".to_string(),
            },
        };

        MusicalIntentCard {
            regime,
            intent_scores,
            directives,
        }
    }

    /// Modulates an existing TuningCard using musical-intent directives.
    pub fn modulate_tuning_card(&self, base_card: &mut TuningCard) {
        let d = &self.directives;
        base_card.recommended_parameters.sub_bass_authority *= d.sub_bass_authority_scale;
        base_card.recommended_parameters.mid_flow_authority *= d.mid_flow_authority_scale;
        base_card.recommended_parameters.transient_desmear *= d.defizz_desmear_scale;
        base_card.recommended_parameters.phase_continuity *= d.defizz_desmear_scale;
        base_card.recommended_parameters.morphic_shelf_db = base_card.recommended_parameters.morphic_shelf_db.min(d.port_hamiltonian_shelf_db);
        base_card.recommended_parameters.morphic_coupling_kappa = d.port_hamiltonian_kappa;
        base_card.recommended_parameters.morphic_quartic_beta = d.port_hamiltonian_beta;
        base_card.recommended_parameters.glue_ratio = d.glue_compressor_ratio;
        base_card.recommended_parameters.glue_threshold_db = d.glue_compressor_threshold_db;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::assess::SceneAssessor;
    use crate::native_audio::Audio;
    use crate::native_dsp::RATE;
    use std::f32::consts::PI;

    #[test]
    fn test_warm_acoustic_song_triggers_preserve_regime() {
        // Synthesize an intimate warm acoustic track: high correlation, gentle roll-off, wide dynamic spread
        let samples = RATE as usize * 4;
        let mut left = vec![0.0f32; samples];
        let mut right = vec![0.0f32; samples];

        for i in 0..samples {
            let t = i as f32 / RATE as f32;
            // Natural warm acoustic harmonic series (150 Hz fundamental with 1/k decay)
            let mut harm = 0.0f32;
            for k in 1..=120 {
                let f = 150.0 * k as f32;
                harm += (2.0 * PI * f * t).sin() * (0.35 / (k as f32).powf(0.85));
            }
            // Wide macro-dynamic amplitude modulation (swelling dynamics)
            let amp = 0.2 + 0.8 * (2.0 * PI * 0.25 * t).sin().abs();
            // Natural room air / acoustic breath
            let air = ((i as f32 * 1337.0).sin() * 0.004) * amp;
            let sig = harm * amp + air;
            left[i] = sig;
            right[i] = sig * 0.98 + (sig * 0.02); // tight center
        }

        let audio = Audio {
            rate: RATE,
            channels: vec![left, right],
        };

        let assessor = SceneAssessor::default();
        let profile = assessor.assess(&audio);
        let stats = SceneStats::compute_from_audio(&audio);
        let intent = MusicalIntentCard::analyze(&profile, &stats);
        eprintln!(
            "DEBUG: sub_instability={}, phase_haze={}, organic_warmth={}, dynamic_budget={}",
            profile.artifacts.sub_instability,
            profile.artifacts.phase_haze,
            intent.intent_scores.organic_warmth_factor,
            intent.intent_scores.dynamic_contrast_budget,
        );
        assert_eq!(intent.regime, MusicalRegime::Preserve);
        assert!(intent.intent_scores.intimacy_score > 0.60);
        assert!(intent.directives.port_hamiltonian_shelf_db <= 0.80);
    }

    #[test]
    fn test_out_of_phase_sub_bass_triggers_restore_regime() {
        // Synthesize severely degraded out-of-phase sub mud
        let samples = RATE as usize * 4;
        let mut left = vec![0.0f32; samples];
        let mut right = vec![0.0f32; samples];

        for i in 0..samples {
            let t = i as f32 / RATE as f32;
            let sub = (2.0 * PI * 45.0 * t).sin() * 0.5;
            let mid = (2.0 * PI * 1000.0 * t).sin() * 0.2;
            left[i] = mid + sub;
            right[i] = mid - sub; // Severe 180° out-of-phase sub mud
        }

        let audio = Audio {
            rate: RATE,
            channels: vec![left, right],
        };

        let assessor = SceneAssessor::default();
        let profile = assessor.assess(&audio);
        let stats = SceneStats::compute_from_audio(&audio);
        let intent = MusicalIntentCard::analyze(&profile, &stats);

        assert_eq!(intent.regime, MusicalRegime::Restore);
        assert_eq!(intent.directives.sub_bass_authority_scale, 1.00);
    }
}
